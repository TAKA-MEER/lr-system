import json


def build_stage1_prompt(chunk_text: str) -> str:
    """
    Stage1: 会話チャンクから要点JSONを抽出するプロンプト
    """
    return f"""あなたは工場立会試験の議事録作成者です。
以下の会話録から情報を抽出し、JSON形式のみで出力してください。

話者ルール:
- our_side: 自社（承認・回答・対応を行う側）
- client: 相手方（要望・確認・指摘を行う側）

重要: 会話中で期限や納期（「〜日までに」「〜までに対応」等）を伴う約束・対応が述べられた場合は、
その協議事項がすでに"合意済み"であっても、必ずaction_itemsにも同じ内容を1件追加すること。
「合意した」ことと「まだ実行していない対応が残っている」ことは別であり、期限付きの
未実施対応はdiscussionsのstatusに関わらずすべてaction_itemsに含める。

重要: 1つの会話チャンクの中に複数の異なる試験項目・指摘事項（例:絶縁抵抗試験、耐電圧試験、
シーケンス動作試験、インターロック試験は、たとえ同じ話題の流れで連続して登場していても
それぞれ別の試験項目である）が含まれる場合は、たとえ話題が連続して登場していても、
必ずそれぞれを個別のdiscussionsエントリとして分けて抽出すること。異なる試験項目の
client_request・our_response・statusを1つのdiscussionにまとめて記述してはならない。
特にstatusは、そのtopic単体について会話中で述べられた状態のみに基づいて個別に判定し、
別の試験項目の状態（例:一方が「継続協議」でももう一方は「合意済み」）を混同しないこと。

statusの判定基準:
- 合意済み: 双方が結論に同意した(試験の合格判定、対応方法への了承を含む)。
- 継続協議: 結論が出ておらず、見積もり・調査・社内確認などを経て、引き続き協議する。
- 保留: 判断を保留すると明言された、または外部の結果待ちなどで判断をいったん止めている。
- 会話中で「合意」「継続協議」「保留」と明言された場合は、その言葉に従う。
- いったん合意した事項について、合意の取り消し・見直しが述べられた場合は、その時点の状態(継続協議など)にする。

重要: client_request と our_response には、会話中に出てきた測定値・規格値・判定値・数量を
単位付きで省略せずに書くこと(例:「絶縁抵抗3.2メガオーム、下限2メガオーム」)。
「合格」「問題なし」だけで数値を落としてはならない。

重要: deadline には会話で述べられた期限の表現をそのまま書くこと(例:「10月9日」「来週の金曜日」
「次回の立会試験まで」)。年を補ったり、日付を別の日付に直したり、推測で日付を作ったりしてはならない。
期限の言及がなければ空文字にする。

抽出するJSON構造:
{{
  "discussions": [
    {{
      "topic": "話題の件名（5〜15文字程度の名詞句。例:「絶縁抵抗試験」「表示灯の色」「銘板の誤記」。同じ話題が会話中に複数回登場する場合は、毎回まったく同じ表現を使うこと。言い換えや装飾語の追加はしない）",
      "client_request": "相手方の要望・質問・指摘（なければ空文字）",
      "our_response": "自社の回答・承認・対応（なければ空文字）",
      "status": "合意済み または 継続協議 または 保留"
    }}
  ],
  "action_items": [
    {{
      "content": "対応内容（対応する discussions の topic と同じ名詞句を含めること）",
      "owner": "our_side または client（実際にその対応を実施する側。相手方に何かを提出・送付するのは自社なら owner は our_side）",
      "deadline": "期限（会話の表現のまま。言及がなければ空文字）"
    }}
  ]
}}

会話:
{chunk_text}

JSONのみ出力。前置き・説明・コードブロック記号は不要。"""


def build_stage2_prompt(summaries: list[str], meta: dict) -> str:
    """
    Stage2: 複数の要点JSONを統合して最終議事録JSONを生成するプロンプト
    """
    n = len(summaries)
    summaries_text = "\n\n".join(
        f"### 要点JSON {i + 1}/{n}(時系列で{i + 1}番目)\n{s}" for i, s in enumerate(summaries)
    )

    return f"""以下の複数の要点JSONを統合し、最終議事録JSONを生成してください。

統合ルール:
- topicの文字列が完全一致していなくても、同一の試験項目・指摘事項・議題を指している場合は
  同一の協議事項とみなし、1件に統合すること（例:「絶縁抵抗試験」と「絶縁抵抗の確認」は同じ話題）
- 重要: 「A盤の絶縁抵抗試験」と「B盤の絶縁抵抗試験」のように、試験の種類は同じでも対象
  （盤・回路・号機など）が異なる場合は、別々の協議事項として扱い、絶対に1件に統合しない
  こと。対象が異なれば結果や結論も異なることが多いため、統合すると誤った状態を報告する
  ことになる。
- 同一の協議事項が複数のJSONにまたがって登場する場合、client_request/our_responseは
  最も情報量が多い（具体的な）記述を採用すること。
- 重要: statusは、その協議事項について状態が述べられた記述のうち、時系列で最も後(番号が大きい)の
  要点JSONの記述を採用すること。例:「継続協議」の後の要点JSONで「合意済み」になっていれば合意済み。
  逆に「合意済み」の後の要点JSONで合意の取り消し・見直しにより「継続協議」になっていれば継続協議。
  後の要点JSONでその話題に軽く触れているだけで、状態の変化が述べられていない場合は、前の状態のままにする。
- client_request / our_response に含まれる測定値・規格値・数量は、統合しても省略せずに残すこと
- deadline は要点JSONに書かれた表現をそのまま使い、年を補ったり日付を書き換えたりしないこと
- action_itemsについても同様に、同一の対応内容が複数回言及されている場合は1件に統合する
- 話題は時系列順に並べる

メタ情報:
- 試験名: {meta.get('trial_name', '')}
- 日時: {meta.get('date', '')}
- 場所: {meta.get('location', '')}
- 相手方参加者: {', '.join(meta.get('attendees', {}).get('client', []))}
- 自社参加者: {', '.join(meta.get('attendees', {}).get('our_side', []))}

要点JSONs:
{summaries_text}

出力するJSON構造:
{{
  "trial_name": "試験名",
  "date": "日時",
  "location": "場所",
  "attendees": {{
    "client": ["氏名"],
    "our_side": ["氏名"]
  }},
  "discussions": [
    {{
      "topic": "議題",
      "client_request": "相手方要望・確認事項",
      "our_response": "自社回答・対応",
      "status": "合意済み または 継続協議 または 保留"
    }}
  ],
  "action_items": [
    {{
      "content": "対応内容",
      "owner": "our_side または client",
      "deadline": "期限(要点JSONの表現のまま)。なければ空文字"
    }}
  ]
}}

JSONのみ出力。前置き・説明・コードブロック記号は不要。"""
